// ──────────────────────────────────────────────────────────────
// A very small PDF writer.
//
// Why not a library. This project has four runtime dependencies — next, react,
// react-dom and Neon's driver — and PR 2.1 treated adding the fourth as a
// supply-chain decision worth a paragraph. The PDF options are worse than that
// trade suggests: headless Chrome is far past Vercel's function size limit, and
// the lighter renderers still pull tens of megabytes of font and layout code to
// produce what this report actually needs, which is text in two weights, filled
// rectangles and rules.
//
// The other half of the reason is that a PDF is the *second* serialisation of a
// scan report, and PR 2.3 spent its whole length making the first one safe. A
// generator whose output nobody can inspect would be a second way to leak the
// prompts. Everything here is plain, uncompressed PDF 1.4, so
// `scripts/verify-report.ts` can search the generated bytes for a withheld
// prompt the same way `verify-paywall.ts` searches the JSON.
//
// Scope, deliberately: the base-14 fonts (Helvetica and Helvetica-Bold), which
// every reader has and which therefore need no embedding; WinAnsi text;
// rectangles and lines. No images, no transparency, no compression. That is the
// whole feature set the report uses.
// ──────────────────────────────────────────────────────────────

export type FontName = "regular" | "bold";

/** A4 in PostScript points, the unit PDF measures in. */
export const PAGE_WIDTH = 595.28;
export const PAGE_HEIGHT = 841.89;

// ── Font metrics ─────────────────────────────────────────────────────────
//
// Widths in 1/1000 em for ASCII 32–126, from the Adobe AFM files for the
// base-14 fonts. Only the printable ASCII range is carried: it is what the
// report contains after transliteration, and a full 256-entry table would be
// mostly zeroes. Anything outside the range measures as 500, which is close
// enough for the wrapping decision and never wrong in a way a reader sees.

